"""Scaffold new modules from a template (and optionally seed from the OSINT catalog).

Mechanical codegen only - no AI, no execution. It writes a ready-to-edit module
skeleton into the external/private module path so new modules start out of tree.
It refuses exploit/payload types: the scaffolder is for auxiliary/post only, which
keeps the "no exploit generation" line intact even for the generator.
"""
from __future__ import annotations

import os
import re
from pathlib import Path
from typing import Any

_BASES = {"auxiliary": "Auxiliary", "post": "Post"}
_BLOCKED = {"exploit", "payload", "encoder"}

# OSINT input type -> (passive option name, kind). Passive names (not RHOSTS/
# RHOST/TARGET) so the generated module is NOT scope-gated, matching OSINT opsec.
_INPUT_OPTION = {
    "username": ("QUERY", "string", "username to look up"),
    "domain": ("DOMAIN", "string", "domain to look up"),
    "email": ("QUERY", "string", "email address to look up"),
    "ip": ("HOST", "string", "IP or host to look up"),
    "phone": ("QUERY", "string", "phone number to look up"),
    "name": ("QUERY", "string", "name/keywords to look up"),
}

_TEMPLATE = '''"""{desc}
{seed}
Generated by `erebus module new`. Edit the TODO in run() to implement it.
"""
from __future__ import annotations

from erebus.core.module_base import {base}, Rank
from erebus.core.options import OptionSpec


class {cls}({base}):
    name = "{name}"
    description = "{desc_short}"
    authors = ["{author}"]
    references = [{refs}]
    attack = [{attack}]
    rank = Rank.NORMAL
    options = [
{options}
    ]

    def run(self) -> None:
{body}
'''


def _camel(text: str) -> str:
    parts = re.split(r"[^a-zA-Z0-9]+", text)
    return "".join(p[:1].upper() + p[1:] for p in parts if p) or "Module"


def _detect_input(tool_input: str) -> str:
    low = (tool_input or "").lower()
    for key in ("username", "domain", "email", "phone"):
        if key in low:
            return key
    if "ip" in low:
        return "ip"
    if "name" in low:
        return "name"
    return ""


def resolve_option(mtype: str, osint_tool: Any = None) -> tuple[str, str, str]:
    """Return (option_name, kind, desc) for an auxiliary module's input option.
    Post modules use a fixed SESSION option instead (handled in render)."""
    if osint_tool is not None:
        det = _detect_input(getattr(osint_tool, "input", ""))
        if det in _INPUT_OPTION:
            return _INPUT_OPTION[det]
    return ("QUERY", "string", "input")


def render_module(key: str, *, author: str = "you", osint_tool: Any = None,
                  drafted_body: str | None = None) -> str:
    """Render a module skeleton for ``<type>/<name>`` (e.g. auxiliary/gather/foo)."""
    parts = [p for p in key.strip().strip("/").split("/") if p]
    if len(parts) < 2:
        raise ValueError("key must be '<type>/<name>', e.g. auxiliary/gather/foo")
    mtype, name = parts[0].lower(), "/".join(parts[1:])
    if mtype in _BLOCKED:
        raise ValueError(
            f"the scaffolder does not generate {mtype!r} modules (auxiliary/post only)")
    if mtype not in _BASES:
        raise ValueError(f"unknown type {mtype!r}; use one of {sorted(_BASES)}")
    base = _BASES[mtype]
    cls = _camel(parts[-1]) + ("Post" if mtype == "post" else "")

    desc_short = f"TODO: describe {name}"
    seed = ""
    refs = ""
    attack = ""
    if osint_tool is not None:
        t = osint_tool
        desc_short = (getattr(t, "description", "") or f"TODO: describe {name}")[:110]
        refs = repr(getattr(t, "url", "")) if getattr(t, "url", "") else ""
        notes = []
        if getattr(t, "name", ""):
            notes.append(f"Seeded from OSINT Framework: {t.name}")
        if getattr(t, "registration", False):
            notes.append("NOTE: upstream requires registration/an API key (use the vault).")
        if getattr(t, "api", False):
            notes.append("Upstream exposes an API - call it in run() within its ToS.")
        if getattr(t, "opsec", "") == "active":
            notes.append("OPSEC active upstream - consider scope implications.")
        seed = ("\n" + "\n".join(notes) + "\n") if notes else ""

    if mtype == "post":
        options = ('        OptionSpec("SESSION", required=True, kind="int",\n'
                   '                   desc="id of a live session"),')
        body = ('        sess = self.get_session()\n'
                '        if sess is None:\n'
                '            return\n'
                '        # TODO: act on the session (read-only/advisory).\n'
                f'        self.info_("{name}: not implemented yet")')
    else:
        opt_name, kind, odesc = resolve_option(mtype, osint_tool)
        options = (f'        OptionSpec("{opt_name}", required=True, kind="{kind}",\n'
                   f'                   desc="{odesc}"),')
        body = f'        # TODO: implement. {opt_name} is passive (not scope-gated).\n' \
               f'        self.info_("{name}: not implemented yet")'

    if drafted_body is not None:
        body = drafted_body
        banner = ("\nAI-DRAFTED - REVIEW BEFORE USE. This run() body was drafted by an "
                  "LLM from the module description; read every line, confirm it is "
                  "passive and in-scope, and test it before trusting it. Not auto-loaded.\n")
        seed = banner + seed

    return _TEMPLATE.format(
        desc=desc_short, seed=seed, base=base, cls=cls, name=name,
        desc_short=desc_short.replace('"', "'"), author=author,
        refs=refs, attack=attack, options=options, body=body)


def default_module_dir() -> Path:
    env = os.environ.get("EREBUS_MODULE_PATH", "")
    if env:
        first = env.split(os.pathsep)[0].strip()
        if first:
            return Path(first).expanduser()
    return Path(os.environ.get("EREBUS_HOME", "~/.erebus")).expanduser() / "modules"


def write_module(key: str, *, out_dir: Path | None = None, author: str = "you",
                 osint_tool: Any = None, force: bool = False,
                 drafted_body: str | None = None) -> Path:
    """Render + write a module skeleton; returns the path. Won't overwrite unless force."""
    code = render_module(key, author=author, osint_tool=osint_tool,
                         drafted_body=drafted_body)
    base = out_dir or default_module_dir()
    fname = key.strip().strip("/").split("/")[-1] + ".py"
    base.mkdir(parents=True, exist_ok=True)
    path = base / fname
    if path.exists() and not force:
        raise FileExistsError(f"{path} exists (use --force to overwrite)")
    path.write_text(code, encoding="utf-8")
    return path
