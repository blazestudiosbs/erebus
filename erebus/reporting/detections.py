"""Purple-team detection export: turn ATT&CK coverage into defensive output.

For every technique Erebus's modules cover (and especially the ones an operation
has *exercised*), this produces a blue-team companion: which telemetry to watch
and a portable **Sigma-style** rule skeleton to deploy. It reuses the bundled
technique -> tactic / name / data-source maps, so there is one source of truth.

Honest framing: the emitted rules are **starting points** keyed to the technique's
data source, meant to be tuned to your environment - not turnkey, high-fidelity
detections. Generating a detection is the defender's half of the purple-team loop.
"""
from __future__ import annotations

from typing import Any

from ..attackmatrix import build_attack_matrix
from .attack import datasources_of, name_of, tactic_of

# Map an ATT&CK data source to a Sigma logsource and a plain "watch for" line.
# Primary source wins; anything unmapped falls back to a generic log review.
_SOURCE_LOGSOURCE: dict[str, dict[str, str]] = {
    "Command Execution": {"category": "process_creation",
                          "watch": "command lines and parent/child process chains"},
    "Process Creation": {"category": "process_creation",
                         "watch": "newly created processes and their arguments"},
    "Process Access": {"category": "process_access",
                       "watch": "handle opens against sensitive processes"},
    "OS API Execution": {"category": "process_creation",
                         "watch": "API calls / tooling that reach sensitive OS functions"},
    "Script Execution": {"category": "ps_script",
                         "watch": "script-block content and interpreter invocations"},
    "Network Traffic": {"category": "network_connection",
                        "watch": "connection volume, fan-out and unusual destinations"},
    "Authentication Logs": {"category": "authentication",
                            "watch": "failed and successful auth bursts per account/source"},
    "Application Log": {"category": "application",
                        "watch": "application-level auth and request anomalies"},
    "File Access": {"category": "file_event",
                    "watch": "reads of credential stores and sensitive files"},
    "File Modification": {"category": "file_event",
                          "watch": "writes to autostart / binary / config locations"},
    "Service Creation": {"category": "service_creation",
                         "watch": "new or modified services and their image paths"},
    "Service Metadata": {"category": "service_creation",
                         "watch": "service image path / hijack changes"},
    "Driver Load": {"category": "driver_load", "watch": "unsigned or unusual driver loads"},
    "Module Load": {"category": "image_load", "watch": "DLL/module loads from odd paths"},
    "Process Metadata": {"category": "process_creation",
                         "watch": "token / integrity-level changes on processes"},
    "Internet Scan": {"category": "external",
                      "watch": "externally observable scanning of your estate (not host-local)"},
    "Malware Repository": {"category": "external",
                           "watch": "third-party intel on infrastructure/tooling (not host-local)"},
    "Cloud Service": {"category": "cloud_audit",
                      "watch": "cloud audit logs for enumeration API calls"},
}

_FALLBACK = {"category": "application", "watch": "relevant logs for this activity"}


def _primary_logsource(data_sources: list[str]) -> dict[str, str]:
    for ds in data_sources:
        if ds in _SOURCE_LOGSOURCE:
            return _SOURCE_LOGSOURCE[ds]
    return _FALLBACK


def _attack_tag(tactic: str, tid: str) -> list[str]:
    tac = tactic.lower().replace(" ", "_").replace("-", "_")
    tags = [f"attack.{tac}"] if tac and tac != "uncategorized" else []
    tags.append("attack." + tid.lower().replace(".", "_"))
    return tags


def render_sigma(entry: dict[str, Any]) -> str:
    """Render one detection entry as a Sigma-style YAML rule (hand-formatted, no deps)."""
    tid, name, tactic = entry["id"], entry["name"], entry["tactic"]
    category = entry["logsource"]["category"]
    watch = entry["watch"]
    sources = ", ".join(entry["data_sources"]) or "general telemetry"
    lines = [
        f"title: Erebus starting point - {name} ({tid})",
        f"id: erebus-{tid.lower().replace('.', '-')}",
        "status: experimental",
        "description: >-",
        f"  Watch {watch} for {name}. Data sources: {sources}. Generated by",
        "  Erebus as a tuning starting point for this technique, not a turnkey rule.",
        "logsource:",
        f"  category: {category}",
        "detection:",
        "  selection:",
        f"    # TODO tune: key fields for {sources}",
        "  condition: selection",
        "falsepositives:",
        "  - Legitimate administrative or authorized testing activity",
        "level: medium",
        "tags:",
        *[f"  - {t}" for t in _attack_tag(tactic, tid)],
    ]
    return "\n".join(lines) + "\n"


def _entry_for(tid: str, exercised: bool) -> dict[str, Any]:
    ds = datasources_of(tid)
    ls = _primary_logsource(ds)
    entry = {
        "id": tid, "name": name_of(tid), "tactic": tactic_of(tid),
        "exercised": exercised, "data_sources": ds,
        "logsource": {"category": ls["category"]}, "watch": ls["watch"],
    }
    entry["sigma"] = render_sigma(entry)
    return entry


def detections_for_techniques(technique_ids: Any) -> list[dict[str, Any]]:
    """Detection entries for a given set of technique ids, built WITHOUT the module
    loader — from the bundled technique maps alone. Used by the per-operation report,
    whose exercised techniques come from an archived logbook, not the live catalogue.
    """
    ids = sorted({str(t).strip().upper() for t in (technique_ids or []) if str(t).strip()})
    return [_entry_for(tid, exercised=True) for tid in ids]


def build_detections(loader: Any, store: Any) -> dict[str, Any]:
    """Build the purple-team detection set from the ATT&CK coverage matrix.

    Returns ``{detections, stats}`` with one entry per covered technique, exercised
    ones first, each carrying its logsource, what to watch, and a Sigma skeleton.
    """
    matrix = build_attack_matrix(loader, store)
    detections: list[dict[str, Any]] = []
    for tac in matrix["tactics"]:
        for e in tac["techniques"]:
            ls = _primary_logsource(e["data_sources"])
            entry = {
                "id": e["id"], "name": e["name"], "tactic": tac["tactic"],
                "exercised": e["exercised"], "jobs": e["jobs"], "findings": e["findings"],
                "data_sources": e["data_sources"],
                "logsource": {"category": ls["category"]},
                "watch": ls["watch"],
            }
            entry["sigma"] = render_sigma(entry)
            detections.append(entry)
    # exercised first (the priority detections), then by id
    detections.sort(key=lambda d: (not d["exercised"], d["id"]))
    stats = {
        "techniques": len(detections),
        "exercised": sum(1 for d in detections if d["exercised"]),
        "data_sources": len({s for d in detections for s in d["data_sources"]}),
    }
    return {"detections": detections, "stats": stats}


def render_markdown(data: dict[str, Any]) -> str:
    """A defensive companion document: the detection set as Markdown."""
    s = data["stats"]
    out = ["# Erebus purple-team detections", "",
           f"{s['techniques']} technique(s) · {s['exercised']} exercised · "
           f"{s['data_sources']} data source(s).", "",
           "Starting points keyed to each technique's ATT&CK data source — tune to "
           "your environment before deploying.", ""]
    for d in data["detections"]:
        mark = "exercised" if d["exercised"] else "covered"
        out.append(f"## {d['id']} — {d['name']}  ({d['tactic']}, {mark})")
        out.append(f"- **Watch:** {d['watch']}")
        out.append(f"- **Data sources:** {', '.join(d['data_sources']) or '—'}")
        out.append("```yaml")
        out.append(d["sigma"].rstrip("\n"))
        out.append("```")
        out.append("")
    return "\n".join(out)
